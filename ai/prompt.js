// ===== 工具手册（渐进式披露：主规则只留目录简述，深度说明按需 read_file；对标 Agent Skills 三层加载） =====
const MANUAL_FILES = ['word文档.md', 'Word排版.md', '表格.md', 'ppt文档.md', '图片视频.md', '设计.md', '网络下载.md', '跨设备协作.md']
function manualsSourceDir() { return path.join(__dirname, 'manuals') }
// 启动释放：把 asar/源码里的手册复制到工作区 ai_manuals/（每次启动覆盖，升级即更新）；失败不抛出，由调用方容错
function releaseManualsTo(workspaceDir) {
  if (!workspaceDir) return ''
  const dst = path.join(workspaceDir, 'ai_manuals')
  fs.mkdirSync(dst, { recursive: true })
  let names = MANUAL_FILES
  try { names = fs.readdirSync(manualsSourceDir()).filter((f) => f.endsWith('.md')) } catch {}
  for (const f of names) { try { fs.copyFileSync(path.join(manualsSourceDir(), f), path.join(dst, f)) } catch {} }
  return dst
}
// 网页版专用：手册全文拼接（网页模型不能 read_file，规则文档直接附全文）
function loadManualsMarkdown() {
  try {
    return fs.readdirSync(manualsSourceDir()).filter((f) => f.endsWith('.md')).sort()
      .map((f) => `\n\n# 工具手册全文·${f.replace(/\.md$/, '')}\n` + fs.readFileSync(path.join(manualsSourceDir(), f), 'utf8')).join('')
  } catch { return '' }
}
